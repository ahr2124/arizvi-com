"""Builds src/data/songs150.ts, the data for the class on /bucknell (ANOP 102, week 11, class 2: playlists or radio?).

Source: "Most Streamed Spotify Songs 2024" on Kaggle (Nidula Elgiriyewithana), 4,600 tracks, data to mid-June 2024.
The CSV is not kept in this repository. Download it and run:

    python3 -I scripts/songs150.py "Most Streamed Spotify Songs 2024.csv" > src/data/songs150.ts

The cut (Ali's lesson, 17 Nov 2026): one row per track and artist, songs released 1 Jan 2023 to 6 Jun 2024 with
Spotify streams, Spotify playlist count and AirPlay spins all present, the 150 best by All Time Rank (the dataset's
own score across platforms). Rows with a blank count or under 1 million Spotify streams (a zero count, should a
later edition have one) are left out first: they are gaps in the source, not songs nobody played (Ali chose this on 17 Nov 2026,
after a cold read found 8 such rows in the first cut). Months since release count to 15 Jun 2024. Each model is
fitted by ordinary least squares, as Excel's Analysis ToolPak does.
"""
import json, sys
import pandas as pd
import statsmodels.api as sm

df = pd.read_csv(sys.argv[1], encoding='latin1')
num = lambda s: pd.to_numeric(s.astype(str).str.replace(',', ''), errors='coerce')
df['streams'] = num(df['Spotify Streams']) / 1e6
df['playlists'] = num(df['Spotify Playlist Count']) / 1e3
df['radio'] = num(df['AirPlay Spins']) / 1e3
df['rank'] = num(df['All Time Rank'])
df['date'] = pd.to_datetime(df['Release Date'], format='%m/%d/%Y')
c = df[(df['date'] >= '2023-01-01') & (df['date'] <= '2024-06-06')]
c = c.drop_duplicates(subset=['Track', 'Artist']).dropna(subset=['streams', 'playlists', 'radio'])
c = c[(c['streams'] >= 1) & (c['radio'] > 0) & (c['playlists'] > 0)]
c = c.sort_values('rank').head(150).copy()
c['months'] = (pd.Timestamp('2024-06-15') - c['date']).dt.days / 30.44

def fix(s):
    # The CSV is UTF-8 read as Latin-1 in places; undo that where it applies.
    try:
        return s.encode('latin1').decode('utf8')
    except (UnicodeEncodeError, UnicodeDecodeError):
        return s

# Names the source file itself garbles (its accents and some non-Latin titles are broken), set right by hand.
FIXES = {
    ('TEXAS HOLD \'EM', 'Beyonc'): ('TEXAS HOLD \'EM', 'Beyoncé'),
    ('Cupid', 'sped up 8282'): ('Cupid (Twin Ver., sped up)', 'sped up 8282'),
    ('CARNIVAL', ''): ('CARNIVAL', '¥$'),
    ('Prada', 'cass'): ('Prada', 'cassö'),
    ('MI EX TEN', 'KAROL G'): ('MI EX TENÍA RAZÓN', 'KAROL G'),
    ('Acr', 'Shakira'): ('Acróstico', 'Shakira'),
    ('Casca de Bala', 'Thullio'): ('Casca de Bala', 'Thullio Milionário'),
    ('', 'FLI:P'): ('(title unreadable in the source)', 'FLI:P'),
    ('Seg', 'Maluma'): ('Según Quién', 'Maluma'),
    ('Coraz', 'Xavi'): ('Corazón de Piedra', 'Xavi'),
    ('La V', 'Xavi'): ('La Víctima', 'Xavi'),
    ('B', 'Isadora Pompeo'): ('Bênçãos Que Não Têm Fim', 'Isadora Pompeo'),
    ('BESO', 'ROSAL'): ('BESO', 'ROSALÍA'),
    ('MTG QUEM N', 'DJ TOPO'): ('MTG QUEM NÃO QUER SOU EU', 'DJ TOPO'),
    ('kompa pasi', ''): ('kompa pasión', '(artist unreadable in the source)'),
    ('', 'YOASOBI'): ('アイドル (Idol)', 'YOASOBI'),
    ('L', 'Billie Eilish'): ("L'AMOUR DE MA VIE", 'Billie Eilish'),
    ('Thinkin', 'Morgan Wallen'): ("Thinkin' Bout Me", 'Morgan Wallen'),
}
bad = []
def name(track, artist):
    track, artist = fix(track), fix(artist)
    if track.isascii() and artist.isascii():
        return track, artist
    for (t, a), good in FIXES.items():
        if track.startswith(t) and artist.startswith(a):
            return good
    bad.append(f'{track!r} by {artist!r}')
    return track, artist

names = {'radio': 'AirPlay radio plays (thousands)', 'playlists': 'Spotify playlists (thousands)', 'months': 'Months since release'}
models = {}
for key, xs in [('radio', ['radio']), ('playlists', ['playlists']), ('both', ['radio', 'playlists']), ('age', ['radio', 'playlists', 'months'])]:
    m = sm.OLS(c['streams'], sm.add_constant(c[xs])).fit()
    rows = [{'name': 'Intercept' if k == 'const' else names[k], 'coef': round(m.params[k], 4), 'se': round(m.bse[k], 4),
             't': round(m.tvalues[k], 2), 'p': float(f'{m.pvalues[k]:.4g}')} for k in m.params.index]
    models[key] = {'r': round(m.rsquared ** 0.5, 3), 'r2': round(m.rsquared, 3), 'adj': round(m.rsquared_adj, 3), 'n': int(m.nobs), 'rows': rows}

songs = [[*name(r.Track, r.Artist), round(r.streams, 1), round(r.playlists, 1), round(r.radio, 1), round(r.months, 1)] for r in c.itertuples()]
if bad:
    raise SystemExit('Unreadable names, add them to FIXES:\n' + '\n'.join(bad))
print('// Generated by scripts/songs150.py from Kaggle\'s "Most Streamed Spotify Songs 2024" (Nidula Elgiriyewithana).')
print('// Do not edit by hand. Each song: [track, artist, Spotify streams (millions), Spotify playlists (thousands),')
print('// AirPlay radio plays (thousands), months since release]. Models: as Excel\'s Analysis ToolPak prints them.')
print('export type Song = [string, string, number, number, number, number];')
print('export interface Coef { name: string; coef: number; se: number; t: number; p: number }')
print('export interface Model { r: number; r2: number; adj: number; n: number; rows: Coef[] }')
print(f'export const corrRadioPlaylists = {round(c["radio"].corr(c["playlists"]), 2)};')
print(f'export const meanMonths = {round(c["months"].mean(), 1)};')
nf = c[c['Track'] != 'Flowers']
r1 = sm.OLS(nf['streams'], sm.add_constant(nf[['radio']])).fit(); r2 = sm.OLS(nf['streams'], sm.add_constant(nf[['radio', 'playlists']])).fit()
print(f'// Without Flowers: radio alone, then radio with playlists in.')
print(f'export const withoutFlowers = {{ radio: {round(r1.params["radio"], 3)}, r2: {round(r1.rsquared, 3)}, both: {round(r2.params["radio"], 3)} }};')
print('export const models: Record<\'radio\' | \'playlists\' | \'both\' | \'age\', Model> = ' + json.dumps(models, ensure_ascii=False, indent=1) + ';')
print('export const songs: Song[] = [')
for s in songs:
    print('  ' + json.dumps(s, ensure_ascii=False) + ',')
print('];')
