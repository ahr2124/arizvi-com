"""Builds src/data/eras250.ts, the data for class 2 on /meowdle (ANOP 102, week 11, class 2: who gets the credit?).

The 250 artist eras are simulated, the same ones as Ali's class Sheet ("Who gets the credit? 250 artist eras") and his
Colab notebook of 20 Nov 2026 (numpy, seed 42). An era is one album cycle for one artist. The recipe, in the order the
notebook draws it:

    fan base       = Normal(5, 2)
    teen exposure  = 0.65 x fan base + Normal(0, 1.4)
    radio ($100k)  = 0.45 x fan base + Uniform(1, 8)
    weekly streams = 8 + 1.4 x teen exposure + 1.1 x radio + 4.2 x fan base + Normal(0, 2.5)   (millions)

Run:

    python3 -I scripts/eras250.py > src/data/eras250.ts

The three steps of the class are fitted by ordinary least squares, as LINEST does: radio alone; radio and teen
exposure; radio, teen exposure and fan base. They reproduce the deck and the Sheet: radio 3.02, then 1.99, then 1.08
(the recipe's 1.1), R squared 0.34, 0.69, 0.96.
"""
import json
import numpy as np

np.random.seed(42)
n = 250
fan = np.random.normal(5, 2, n)
teen = 0.65 * fan + np.random.normal(0, 1.4, n)
radio = 0.45 * fan + np.random.uniform(1, 8, n)
streams = 8 + 1.4 * teen + 1.1 * radio + 4.2 * fan + np.random.normal(0, 2.5, n)


def fit(cols):
    X = np.column_stack([np.ones(n)] + cols)
    b, *_ = np.linalg.lstsq(X, streams, rcond=None)
    r2 = 1 - ((streams - X @ b) ** 2).sum() / ((streams - streams.mean()) ** 2).sum()
    return [round(float(v), 4) for v in b], round(float(r2), 4)


(a1, r1), q1 = fit([radio])
(a2, r2_, t2), q2 = fit([radio, teen])
(a3, r3, t3, f3), q3 = fit([radio, teen, fan])
steps = {
    'step1': {'intercept': a1, 'radio': r1, 'r2': q1},
    'step2': {'intercept': a2, 'radio': r2_, 'teen': t2, 'r2': q2},
    'step3': {'intercept': a3, 'radio': r3, 'teen': t3, 'fan': f3, 'r2': q3},
}
rows = [[round(float(s), 2), round(float(f), 2), round(float(t), 2), round(float(r), 2)] for s, f, t, r in zip(streams, fan, teen, radio)]

print('// Generated by scripts/eras250.py (numpy, seed 42). Do not edit by hand.')
print('// 250 simulated artist eras for class 2 on /meowdle, the same as the class Sheet. Each row:')
print('// [weekly streams (millions), fan base, teen exposure, radio spend ($100k)], rounded to 2 decimals for the chart.')
print('// The steps are fitted on the full-precision data, as LINEST does in the Sheet.')
print(f'export const eras: [number, number, number, number][] = {json.dumps(rows, separators=(",", ":"))};')
print(f'export const steps = {json.dumps(steps)};')
print(f"export const means = {json.dumps({'teen': round(float(teen.mean()), 4), 'fan': round(float(fan.mean()), 4)})};")
print(f"export const corr = {json.dumps({'radioFan': round(float(np.corrcoef(radio, fan)[0, 1]), 4), 'teenFan': round(float(np.corrcoef(teen, fan)[0, 1]), 4)})};")
print(f'export const maxRadio = {round(float(radio.max()), 4)};')
